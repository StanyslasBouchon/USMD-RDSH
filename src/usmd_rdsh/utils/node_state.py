from enum import Enum


class NodeState(Enum):
    """Node state enumeration."""

    APPROVAL_REQUIRED = 0x0000
    SYNCHRONISING = 0x1000
    ACTIVE = 0x2000
    INACTIVE = 0x3000
    INACTIVE_MUTATING = 0x3100
    INACTIVE_TIMEOUT = 0x3200
    INACTIVE_URGE = 0x3300
    INACTIVE_URGE_ROOR = 0x3301  # Running out of resources
    INACTIVE_URGE_INACTIVE_DEPENDENCIES = 0x3302  # Inactive dependencies
    INACTIVE_URGE_HEALTH_CHECK_FAILED = 0x3303  # Health check failed
    INACTIVE_URGE_UPDATE_FAILED = 0x3304  # Update failed
    INACTIVE_NNDP_HERE_I_AM_TIMEOUT = 0x3400
    KICKED_INVALID_NIT_ASSOCIATION = 0x4000
    KICKED_INVALID_ENDORSEMENT_PACKET = 0x4100
    KICKED_UNCHECKABLE_ENDORSEMENT_PACKET = 0x4200
    KICKED_INVALID_NEL_REVOCATION = 0x4300
    KICKED_INVALID_ENDORSEMENT_PACKET_REVOCATION = 0x4400
